/**
 * @file scripts/plugin-release-assets.mjs
 * @project SlothVault
 * @module Application Plugin Release Assets
 * @description Packages every source plugin and defines the complete application Release attachment contract.
 * @logic Discover committed plugin identities, reuse the source-only packer, aggregate checksums, and validate all required assets before publication.
 * @dependencies Node filesystem/crypto, plugin source packer (packaging only)
 * @index_tags plugins,release,source,checksums,application
 * @author holic512
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { copyFile, mkdir, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const versionPattern = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/
const pluginIdPattern = /^[a-z][a-z0-9]*(?:[.-][a-z0-9]+)+$/
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
export function pluginAssetsEnabled(metadata) {
  const value = metadata.slothvaultRelease?.pluginAssets
  if (value !== undefined && typeof value !== 'boolean') throw new Error('slothvaultRelease.pluginAssets must be a boolean')
  return value === true
}

/** Source package inputs, including the metadata that must match the manifest version. */
export function isPluginPackageFile(file) {
  return /^plugins\/[^/]+\/(?:plugin(?:\.build)?\.json$|package\.json$|src\/)/.test(file)
}

export function discoverReleasePlugins(root) {
  const plugins = readdirSync(join(root, 'plugins'), { withFileTypes: true }).flatMap(entry => {
    const directory = `plugins/${entry.name}`
    if (!existsSync(join(root, directory, 'plugin.json'))) return []
    if (!entry.isDirectory()) throw new Error(`Plugin source must be a real directory: ${directory}`)
    const manifest = JSON.parse(readFileSync(join(root, directory, 'plugin.json'), 'utf8'))
    const metadata = JSON.parse(readFileSync(join(root, directory, 'package.json'), 'utf8'))
    if (!pluginIdPattern.test(manifest.id) || !versionPattern.test(manifest.version)
      || !manifest.version.split('.').every(part => Number.isSafeInteger(Number(part)))) throw new Error(`Invalid plugin identity: ${directory}`)
    if (manifest.version !== metadata.version) throw new Error(`Plugin package/manifest versions differ: ${directory}`)
    return [{ directory, name: entry.name, id: manifest.id, version: manifest.version, asset: `slothvault-plugin-${manifest.id}-${manifest.version}.zip` }]
  }).sort((a, b) => a.id.localeCompare(b.id))
  if (!plugins.length) throw new Error('Application Release must contain at least one source plugin')
  if (new Set(plugins.map(plugin => plugin.id)).size !== plugins.length) throw new Error('Duplicate plugin IDs in application Release')
  return plugins
}

/** No npm/archiver import here: the publish runner only needs Node and the pinned source. */
export function applicationReleaseAssets(root, outdir) {
  const assets = [join(outdir, 'slothvault-image-manifest.json')]
  const metadata = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  if (pluginAssetsEnabled(metadata)) {
    const plugins = discoverReleasePlugins(root)
    const checksumPath = join(outdir, 'checksums.sha256')
    const lines = readFileSync(checksumPath, 'utf8').trim().split(/\r?\n/)
    const checksums = new Map()
    for (const line of lines) {
      const match = /^([a-f0-9]{64})  (slothvault-plugin-[a-z0-9.-]+-\d+\.\d+\.\d+\.zip)$/.exec(line)
      if (!match || checksums.has(match[2])) throw new Error('Invalid or duplicate plugin release checksum')
      checksums.set(match[2], match[1])
    }
    if (checksums.size !== plugins.length) throw new Error('Plugin release checksums must cover every plugin exactly once')
    for (const plugin of plugins) {
      const path = join(outdir, plugin.asset)
      if (hash(readFileSync(path)) !== checksums.get(plugin.asset)) throw new Error(`Plugin release checksum mismatch: ${plugin.asset}`)
      assets.push(path)
    }
    assets.push(checksumPath)
  }
  // Fail before creating a draft, not halfway through an upload.
  for (const path of assets) readFileSync(path)
  return assets
}

export async function packReleasePlugins({ root = process.cwd() } = {}) {
  const plugins = discoverReleasePlugins(root)
  const { packPlugin } = await import('../plugins/sdk/cli.mjs')
  const output = join(root, 'dist/application/plugins')
  // This directory is exclusively generated by this packer; remove stale versioned ZIPs.
  await rm(output, { recursive: true, force: true })
  await mkdir(output, { recursive: true })
  const checksums = []
  for (const plugin of plugins) {
    const packed = await packPlugin(resolve(root, plugin.directory), join(root, 'dist/plugins', plugin.name))
    await copyFile(packed.path, join(output, plugin.asset))
    checksums.push(`${packed.checksum}  ${plugin.asset}\n`)
  }
  await writeFile(join(output, 'checksums.sha256'), checksums.join(''))
  return { output, plugins }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const result = await packReleasePlugins()
  console.info(`[plugins] Packaged ${result.plugins.length} source plugins without compiling: ${result.output}`)
}
